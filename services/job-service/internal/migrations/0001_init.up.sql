-- job-service schema v1: jobs, requirements, hiring stages, audit log.
-- Owned exclusively by job-service (database: smarthire_jobs).

CREATE TABLE jobs (
    id              UUID PRIMARY KEY,               -- UUIDv7 generated by the app (time-ordered)
    recruiter_id    UUID         NOT NULL,          -- owner; FK to identity service once auth exists
    title           VARCHAR(200) NOT NULL,
    description     TEXT         NOT NULL DEFAULT '',
    department      VARCHAR(100) NOT NULL DEFAULT '',
    location        VARCHAR(150) NOT NULL DEFAULT '',
    employment_type VARCHAR(20)  NOT NULL
        CHECK (employment_type IN ('full_time', 'part_time', 'contract', 'internship', 'temporary')),
    work_mode       VARCHAR(10)  NOT NULL
        CHECK (work_mode IN ('onsite', 'remote', 'hybrid')),
    experience_min  INT CHECK (experience_min >= 0),
    experience_max  INT CHECK (experience_max >= 0),
    salary_min      BIGINT CHECK (salary_min >= 0),
    salary_max      BIGINT CHECK (salary_max >= 0),
    currency        CHAR(3),
    -- Lifecycle. Week 2 adds 'processing' when publishing moves to Temporal.
    status          VARCHAR(20)  NOT NULL DEFAULT 'draft'
        CHECK (status IN ('draft', 'published', 'closed', 'archived')),
    -- Optimistic locking: every write bumps version; writers send the version they read.
    version         INT          NOT NULL DEFAULT 1,
    published_at    TIMESTAMPTZ,
    closed_at       TIMESTAMPTZ,
    created_at      TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at      TIMESTAMPTZ  NOT NULL DEFAULT now(),
    deleted_at      TIMESTAMPTZ,                    -- soft delete (GORM convention)

    CONSTRAINT chk_jobs_experience_range CHECK (experience_min IS NULL OR experience_max IS NULL OR experience_max >= experience_min),
    CONSTRAINT chk_jobs_salary_range     CHECK (salary_min IS NULL OR salary_max IS NULL OR salary_max >= salary_min)
);

-- Partial indexes: soft-deleted rows are never queried, so keep them out of the index.
CREATE INDEX idx_jobs_status     ON jobs (status, created_at DESC) WHERE deleted_at IS NULL;
CREATE INDEX idx_jobs_recruiter  ON jobs (recruiter_id)           WHERE deleted_at IS NULL;
CREATE INDEX idx_jobs_location   ON jobs (lower(location))        WHERE deleted_at IS NULL;

CREATE TABLE job_requirements (
    id           UUID PRIMARY KEY,
    job_id       UUID         NOT NULL REFERENCES jobs (id) ON DELETE CASCADE,
    type         VARCHAR(20)  NOT NULL CHECK (type IN ('skill', 'qualification', 'experience', 'other')),
    value        VARCHAR(255) NOT NULL,
    is_mandatory BOOLEAN      NOT NULL DEFAULT TRUE,
    created_at   TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT uq_job_requirements UNIQUE (job_id, type, value)
);
CREATE INDEX idx_job_requirements_job ON job_requirements (job_id);

CREATE TABLE hiring_stages (
    id          UUID PRIMARY KEY,
    job_id      UUID         NOT NULL REFERENCES jobs (id) ON DELETE CASCADE,
    name        VARCHAR(100) NOT NULL,
    stage_type  VARCHAR(20)  NOT NULL CHECK (stage_type IN ('screening', 'assessment', 'interview', 'offer')),
    position    INT          NOT NULL CHECK (position >= 1),   -- order in the pipeline
    created_at  TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT uq_hiring_stages_position UNIQUE (job_id, position),
    CONSTRAINT uq_hiring_stages_name     UNIQUE (job_id, name)
);

-- Append-only audit trail, written in the same transaction as the change it
-- describes, so the trail can never disagree with the data.
CREATE TABLE audit_logs (
    id           UUID PRIMARY KEY,
    entity_type  VARCHAR(50)  NOT NULL,
    entity_id    UUID         NOT NULL,
    action       VARCHAR(50)  NOT NULL,
    actor_id     VARCHAR(100) NOT NULL DEFAULT 'anonymous',
    changes      JSONB        NOT NULL DEFAULT '{}'::jsonb,
    request_id   VARCHAR(100) NOT NULL DEFAULT '',
    created_at   TIMESTAMPTZ  NOT NULL DEFAULT now()
);
CREATE INDEX idx_audit_logs_entity ON audit_logs (entity_type, entity_id, created_at DESC);
