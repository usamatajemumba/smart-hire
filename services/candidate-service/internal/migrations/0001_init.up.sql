-- candidate-service schema v1: candidates and their profile sections.
-- Owned exclusively by candidate-service (database: smarthire_candidates).

CREATE TABLE candidates (
    id               UUID PRIMARY KEY,              -- UUIDv7 generated by the app
    email            VARCHAR(254) NOT NULL,
    full_name        VARCHAR(150) NOT NULL,
    phone            VARCHAR(30)  NOT NULL DEFAULT '',
    location         VARCHAR(150) NOT NULL DEFAULT '',
    headline         VARCHAR(200) NOT NULL DEFAULT '',  -- e.g. "Backend Engineer, 5y Go"
    summary          TEXT         NOT NULL DEFAULT '',
    years_experience INT          NOT NULL DEFAULT 0 CHECK (years_experience BETWEEN 0 AND 60),
    version          INT          NOT NULL DEFAULT 1,   -- optimistic locking
    created_at       TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at       TIMESTAMPTZ  NOT NULL DEFAULT now(),
    deleted_at       TIMESTAMPTZ
);

-- One active account per email, case-insensitive. Partial so a soft-deleted
-- candidate can register again with the same email.
CREATE UNIQUE INDEX uq_candidates_email ON candidates (lower(email)) WHERE deleted_at IS NULL;
CREATE INDEX idx_candidates_location ON candidates (lower(location)) WHERE deleted_at IS NULL;

CREATE TABLE candidate_skills (
    id           UUID PRIMARY KEY,
    candidate_id UUID         NOT NULL REFERENCES candidates (id) ON DELETE CASCADE,
    name         VARCHAR(100) NOT NULL,
    level        VARCHAR(20)  NOT NULL DEFAULT 'intermediate'
        CHECK (level IN ('beginner', 'intermediate', 'advanced', 'expert')),
    years        INT          NOT NULL DEFAULT 0 CHECK (years BETWEEN 0 AND 60),
    created_at   TIMESTAMPTZ  NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX uq_candidate_skills ON candidate_skills (candidate_id, lower(name));
-- Supports "find candidates with skill X" (recruiter search, Week 2 eligibility checks).
CREATE INDEX idx_candidate_skills_name ON candidate_skills (lower(name));

CREATE TABLE work_experiences (
    id           UUID PRIMARY KEY,
    candidate_id UUID         NOT NULL REFERENCES candidates (id) ON DELETE CASCADE,
    company      VARCHAR(150) NOT NULL,
    title        VARCHAR(150) NOT NULL,
    start_date   DATE         NOT NULL,
    end_date     DATE,                                  -- NULL = current job
    description  TEXT         NOT NULL DEFAULT '',
    created_at   TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT chk_work_dates CHECK (end_date IS NULL OR end_date >= start_date)
);
CREATE INDEX idx_work_experiences_candidate ON work_experiences (candidate_id);

CREATE TABLE educations (
    id             UUID PRIMARY KEY,
    candidate_id   UUID         NOT NULL REFERENCES candidates (id) ON DELETE CASCADE,
    institution    VARCHAR(150) NOT NULL,
    degree         VARCHAR(150) NOT NULL,
    field_of_study VARCHAR(150) NOT NULL DEFAULT '',
    start_year     INT          NOT NULL,
    end_year       INT,
    created_at     TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT chk_education_years CHECK (end_year IS NULL OR end_year >= start_year)
);
CREATE INDEX idx_educations_candidate ON educations (candidate_id);

-- Resume metadata. The file itself lives in blob storage (local volume now,
-- S3/MinIO later); the DB only stores where to find it. Every upload is kept
-- so history is never lost; the newest row is the current resume.
CREATE TABLE resumes (
    id           UUID PRIMARY KEY,
    candidate_id UUID         NOT NULL REFERENCES candidates (id) ON DELETE CASCADE,
    file_name    VARCHAR(255) NOT NULL,
    content_type VARCHAR(100) NOT NULL,
    size_bytes   BIGINT       NOT NULL CHECK (size_bytes > 0),
    storage_key  VARCHAR(500) NOT NULL,
    uploaded_at  TIMESTAMPTZ  NOT NULL DEFAULT now()
);
CREATE INDEX idx_resumes_candidate ON resumes (candidate_id, uploaded_at DESC);

CREATE TABLE audit_logs (
    id           UUID PRIMARY KEY,
    entity_type  VARCHAR(50)  NOT NULL,
    entity_id    UUID         NOT NULL,
    action       VARCHAR(50)  NOT NULL,
    actor_id     VARCHAR(100) NOT NULL DEFAULT 'anonymous',
    changes      JSONB        NOT NULL DEFAULT '{}'::jsonb,
    request_id   VARCHAR(100) NOT NULL DEFAULT '',
    created_at   TIMESTAMPTZ  NOT NULL DEFAULT now()
);
CREATE INDEX idx_audit_logs_entity ON audit_logs (entity_type, entity_id, created_at DESC);
